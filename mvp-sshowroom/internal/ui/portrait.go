func renderArt(art string, width, height int) string {
	if width <= 0 || height <= 0 {
		return ""
	}

	lines := strings.Split(art, "\n")
	maxWidth := 0
	for _, line := range lines {
		if lineWidth := utf8.RuneCountInString(line); lineWidth > maxWidth {
			maxWidth = lineWidth
		}
	}

	scale := min(float64(width)/float64(maxWidth), float64(height)/float64(len(lines)), 1)
	targetHeight := max(1, int(float64(len(lines))*scale))
	var rendered []string
	for y := 0; y < targetHeight; y++ {
		sourceY := min(len(lines)-1, y*len(lines)/targetHeight)
		source := []rune(lines[sourceY])
		lineWidth := max(1, int(float64(len(source))*scale))
		var row strings.Builder
		for x := 0; x < lineWidth; x++ {
			sourceX := min(len(source)-1, x*len(source)/lineWidth)
			row.WriteRune(source[sourceX])
		}
		rendered = append(rendered, row.String())
	}
	return strings.Join(rendered, "\n")
}
